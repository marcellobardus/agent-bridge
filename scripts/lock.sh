#!/bin/bash
# Produce requirements.lock: hash-pinned, wheels only, valid for CPython 3.13 and 3.14,
# Linux x86_64 manylinux. Needs uv (https://docs.astral.sh/uv/) and PyPI access.
# Resolves once per interpreter, requires identical pins, and unions the hashes (a pin may have
# different wheels per interpreter, e.g. cp313 vs cp314). Re-run whenever requirements.in changes.
# Usage (repo root): scripts/lock.sh [requirements.in]
set -euo pipefail
cd "$(dirname "$0")/.."
IN=${1:-requirements.in}
OUT=requirements.lock
command -v uv >/dev/null || { echo "uv not found (needed to lock)" >&2; exit 1; }
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
for v in 3.13 3.14; do
  uv pip compile "$IN" --generate-hashes --python-version "$v" --python-platform x86_64-manylinux_2_28 \
    --only-binary :all: --no-header --quiet -o "$W/r$v.txt"
done
python3 -I - "$W/r3.13.txt" "$W/r3.14.txt" "$IN" > "$OUT" <<'PYEOF'
import re, sys, collections
pins, hashes = {}, collections.defaultdict(set)
for f in sys.argv[1:3]:
    cur = None
    for line in open(f):
        m = re.match(r"^([A-Za-z0-9_.-]+)==(\S+?)\s*\\?$", line)
        if m:
            cur = (m[1].lower(), m[2]); pins.setdefault(cur[0], set()).add(cur[1])
        h = re.search(r"--hash=(sha256:[0-9a-f]{64})", line)
        if h and cur:
            hashes[cur].add(h[1])
for n, vs in pins.items():
    if len(vs) != 1:
        sys.exit(f"{n}: 3.13 and 3.14 resolve to different versions {sorted(vs)}; constrain requirements.in")
print(f"# generated by scripts/lock.sh from {sys.argv[3]} - do not edit. CPython 3.13 + 3.14, manylinux x86_64, wheels only.")
for n in sorted(pins):
    v = next(iter(pins[n])); hs = sorted(hashes[(n, v)])
    print(f"{n}=={v} \\")
    print(" \\\n".join(f"    --hash={h}" for h in hs))
PYEOF
echo "wrote $OUT ($(grep -c '^[a-z]' "$OUT") packages)"
